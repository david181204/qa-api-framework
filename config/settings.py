"""测试配置的中心。

原则：**环境相关的东西只在这里出现一次**。
用例、fixture、接口类都不应该出现 "http://127.0.0.1:8000" 或数据库密码这类字面量。

为什么这么做：
    换环境（本地 → CI → 测试服）时，只改这里或只改环境变量，
    不用在几十个文件里搜索替换。这就是"配置与代码分离"。

注意：目前 DB_URL / BASE_URL 还带有本地默认值。
下一步（第 4 步）会把默认值去掉，改成从 .env 读取 + CI 用 GitHub Secrets，
这样密码就不会出现在代码库里。
"""
import os

# 被测服务地址。CI 里同样是 127.0.0.1:8000，本地不用改；
# 将来部署到测试服只需设置环境变量 BASE_URL。
BASE_URL = os.getenv("BASE_URL", "http://127.0.0.1:8000")

# 数据库连接串。本地 Docker MySQL 映射在 3307；CI 里的 MySQL 是 3306，
# 由 ci.yml 通过环境变量覆盖，代码不需要改动。
DB_URL = os.getenv(
    "DB_URL",
    "mysql+pymysql://root:123456@127.0.0.1:3307/qa_shop?charset=utf8mb4",
)

# 单个请求的超时时间（秒）。
# 不设超时是最常见的低级错误：接口一旦卡住不返回，测试进程会一直挂着，
# 在 CI 里表现就是 job 跑满 6 小时被强制杀掉，而且看不出原因。
TIMEOUT = float(os.getenv("TIMEOUT", "10"))
